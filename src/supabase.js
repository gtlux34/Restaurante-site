
import { createClient } from '@supabase/supabase-js'

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL
const supabaseKey = import.meta.env.VITE_SUPABASE_ANON_KEY

export const supabase = createClient(
  supabaseUrl,
  supabaseKey
)

// Cliente usado apenas pelo painel admin para cadastrar novos clientes.
// Ele não guarda sessão, então o admin continua logado depois do cadastro.
export const supabaseCadastro = createClient(supabaseUrl, supabaseKey, {
  auth: {
    persistSession: false,
    autoRefreshToken: false,
    detectSessionInUrl: false,
    storageKey: 'sb-cadastro-admin',
  },
})